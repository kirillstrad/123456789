export const INTERIOR_FAMILIES=deepFreeze(authored.map(row=>({...row,familyId:'interior.'+row.category+'.'+row.slug})));
const labels={textile:['WORN','TORN'],blood:['TRACE A','TRACE B'],remains:['STATE A','STATE B'],furniture:['WORN','DAMAGED'],storage:['WORN','DAMAGED'],household:['AGED','NEGLECTED'],writing:['AGED','NEGLECTED'],ritual:['AGED','NEGLECTED'],ruin:['FRAGMENT A','FRAGMENT B'],damp:['PATCH A','PATCH B'],decay:['TRACE A','TRACE B'],iron:['WORN','RUSTED']};
export const INTERIOR_CARDS=deepFreeze(INTERIOR_FAMILIES.flatMap(f=>[0,1].map(variant=>({
 modelId:f.familyId+'.'+(variant?'b':'a'),familyId:f.familyId,category:f.category,name:f.name,
 variant,variantLabel:labels[f.category][variant],size:f.width*f.depth>5?'large':f.width*f.depth>1?'medium':'small',
 dimensions:{width:f.width,depth:f.depth,height:f.height},role:f.collision?'decorative-obstacle':'decor',
 collision:f.collision?'footprint':'none',interaction:{type:'none',prompt:null},
 visualAcceptance:'pending',shape:f.shape,feature:f.feature,
}))));
const byId=new Map(INTERIOR_CARDS.map(c=>[c.modelId,c]));
export function interiorCard(id){const card=byId.get(id);if(!card)throw Error('Unknown interior model: '+id);return card;}
export function listInteriorCards(category='all'){
 if(category!=='all'&&!INTERIOR_CATEGORIES.includes(category))throw Error('Unknown interior category: '+category);
 return INTERIOR_CARDS.filter(c=>category==='all'||c.category===category);
}
